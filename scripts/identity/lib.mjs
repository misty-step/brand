/**
 * Everything generate.mjs owns under identity/ (path -> contents), the PNG icons (rendered here, checked by
 * source hash, because rasterisers differ in the last bit across platforms) and the social cards (rendered
 * by og.mjs in a browser on a Linux worker, also checked by source hash).
 */
export async function outputs(data) {
  const { picks, options: o } = data;
  const files = new Map();
  const fonts = o.type.faces.map(face => ({ face, path: fileURLToPath(face.src), file: basename(fileURLToPath(face.src)) }));
  const fontDir = dirname(fonts[0].path);
  if (fonts.some(font => dirname(font.path) !== fontDir)) throw new Error(`type ${picks.type}: faces must share one fonts directory`);
  for (const font of fonts) files.set(`fonts/${font.file}`, await readFile(font.path));
  const licences = (await readdir(fontDir)).filter(name => /^(OFL|LICEN[CS]E|APACHE)/i.test(name)).sort();
  if (!licences.length) throw new Error(`type ${picks.type}: no licence file beside the fonts`);
  for (const name of licences) files.set(`fonts/${name}`, await readFile(join(fontDir, name)));
  files.set('brand.css', stylesheet(data, fonts));
  const locked = { MOTION_HOST: o.hero.motionHost };
  files.set('runtime.js', await bundleBrowser('runtime.ts', picks, locked, { minify: true }));
  files.set('runtime.d.ts', runtimeTypes(o));
  files.set('field.js', await bundleBrowser('field.ts', picks, locked, { minify: true }));
  files.set('attrs.js', await attrsModule(picks));
  files.set('attrs.d.ts', attrsTypes(picks));
  const names = brandNames(o);
  files.set('mark.js', markModule(o, names));
  files.set('mark.d.ts', markTypes(names));
  files.set('icons/favicon.svg', faviconSvg(o, ''));
  const icons = new Map(iconSources(o).map(({ file, source }) => [file, { hash: sha256(RESVG, '\n', source), source }]));
  const fontBytes = fonts.map(font => files.get(`fonts/${font.file}`));
  const og = new Map(OG.pages.map(page => {
    const html = ogPage(data, page);
    return [`og/${page}.png`, { page, html, hash: sha256(html, files.get('runtime.js'), files.get('field.js'), ...fontBytes) }];
  }));
  return { files, icons, og };
}
