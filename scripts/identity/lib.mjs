/** brand.css: faces, tokens for both themes, then the preview's base and each layer's CSS in the preview's order. */
function stylesheet(data, fonts) {
  const { picks, options: o, baseCss } = data;
  const faces = fonts.map(({ face, file }) => `@font-face{font-family:${JSON.stringify(face.family)};src:url(./fonts/${file}) format('woff2');font-weight:${face.weight};font-style:${face.style ?? 'normal'};font-display:swap;${face.unicodeRange ? `unicode-range:${face.unicodeRange};` : ''}}`);
  // The hero's own entrance order, read from its render, so pages without inline styles keep the sequence.
  const sample = o.hero.render({
    page: 'studio', theme: 'light', reducedMotion: false, viewport: 'desktop', content: o.copy.pages.studio.hero,
    brand: o.copy.pages.studio.brand, mark: size => o.mark.svg({ size, title: '' }), wordmark: () => '',
  });
  const order = [...sample.matchAll(/class="([\w-]+)" data-enter style="--enter-i:(\d+)/g)];
  if (order.length !== (sample.match(/data-enter/g) ?? []).length) throw new Error(`hero ${picks.hero}: could not read the entrance order of every [data-enter] piece`);
  const s = `html[data-hero="${picks.hero}"] .hero`;
  return [
    `/* @misty-step/brand: ${NOTICE} Locked: ${LAYERS.map(layer => `${layer} ${picks[layer]}`).join(', ')}. Fonts: ${o.type.license} */`,
    ...faces,
    `html[data-type="${picks.type}"]{${decl(o.type.tokens)}}`,
    `html[data-color="${picks.color}"]{${decl(o.color.light)}}`,
    `html[data-color="${picks.color}"][data-theme="dark"]{${decl(o.color.dark)}}`,
    '/* Until the site sets data-theme, follow the system. */',
    `@media (prefers-color-scheme:dark){html[data-color="${picks.color}"]:not([data-theme]){${decl(o.color.dark)};color-scheme:dark}}`,
    '/* Until the runtime sets data-reduced-motion, honour the system: entrances finished, nothing animates. */',
    '@media (prefers-reduced-motion:reduce){html:not([data-reduced-motion]) [data-enter]{animation:none!important;opacity:1!important;transform:none!important;clip-path:none!important;filter:none!important}html:not([data-reduced-motion]) *,html:not([data-reduced-motion]) *::before,html:not([data-reduced-motion]) *::after{animation-duration:0s!important;transition-duration:0s!important;scroll-behavior:auto!important}}',
    '/* The hero entrance order for pages that cannot use inline styles (strict CSP); inline --enter-i still wins. */',
    order.map(([, cls, i]) => `${s} .${cls}{--enter-i:${i}}`).join('\n'),
    '/* Base: configurator/src/preview/base.css */',
    baseCss.trim(),
    `/* Layout: ${picks.layout} */`,
    o.layout.css.trim(),
    `/* Hero: ${picks.hero} */`,
    o.hero.css.trim(),
    `/* Motion: ${picks.motion}, entrance and interaction */`,
    o.motion.entrance.css.trim(),
    (o.motion.interaction?.css ?? '').trim(),
    `/* Mark: ${picks.mark} */`,
    (o.mark.css ?? '').trim(),
  ].filter(Boolean).join('\n') + '\n';
}

