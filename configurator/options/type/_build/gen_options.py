"""Write options/type/<id>/ (index.ts, fonts/, OFL texts) from options.json and .out/ (step 3 of 3).

    python3 gen_options.py        # after fetch.sh and build_fonts.py

index.ts files are generated: edit options.json (copy, refs, tokens, px sizes) and rerun.
Sizes are given in px at the 390 and 1440 viewports and written as linear clamp() values;
a third number snaps a pixel face's size to whole multiples of its grid with CSS round().
"""
import json
import shutil
from pathlib import Path

from metrics import advance, load

HERE = Path(__file__).parent
SRC = HERE / ".src"
BUILT = HERE / ".out"
DEST = HERE.parent
LATIN = (
    "U+0000-00FF, U+0131, U+0152-0153, U+02BB-02BC, U+02C6, U+02DA, U+02DC, U+0304, U+0308, U+0329, "
    "U+2000-206F, U+20AC, U+2122, U+2190-2193, U+2212, U+2215, U+FEFF, U+FFFD"
)
VW_MIN, VW_MAX = 390, 1440


def r(x):
    s = f"{x:.4f}".rstrip("0").rstrip(".")
    return s if s != "-0" else "0"


def fluid(lo, hi):
    """clamp() from lo px at a 390px viewport to hi px at 1440px."""
    if lo == hi:
        return f"{r(lo / 16)}rem"
    slope = (hi - lo) / (VW_MAX - VW_MIN)
    icpt = lo - slope * VW_MIN
    return f"clamp({r(lo / 16)}rem, {r(icpt / 16)}rem + {r(slope * 100)}vw, {r(hi / 16)}rem)"


def snapped(lo, hi, step):
    """Fluid size rounded to whole multiples of a pixel face's grid (bounds are exact multiples)."""
    slope = (hi - lo) / (VW_MAX - VW_MIN)
    icpt = lo - slope * VW_MIN
    return f"round(nearest, clamp({r(lo)}px, {r(icpt)}px + {r(slope * 100)}vw, {r(hi)}px), {r(step)}px)"


OPTIONS = json.loads((HERE / "options.json").read_text())

TS = """import type {{ TypeOption }} from '../../../src/contract';

// Generated by options/type/_build/gen_options.py from _build/options.json; edit there and rerun.
// {comment}
// --display-advance: average advance per character of the display setting (em, with its weight,
// tracking and transform), measured from the font file; heroes use it to keep h1 to two lines.
type TypeOptionWithAdvance = TypeOption & {{ tokens: TypeOption['tokens'] & {{ '--display-advance'?: string }} }};

const font = (file: string) => new URL(`./fonts/${{file}}`, import.meta.url).href;
const LATIN = '{latin}';

export default {{
  id: '{id}',
  layer: 'type',
  label: {label},
  summary: {summary},
  origin: '{origin}',
  refs: [
{refs}
  ],
  faces: [
{faces}
  ],
  tokens: {{
{tokens}
  }},
  license: {license},
}} satisfies TypeOptionWithAdvance;
"""


def q(s):
    return json.dumps(s, ensure_ascii=False)


def main():
    for opt in OPTIONS:
        d = DEST / opt["id"]
        fonts = d / "fonts"
        if d.exists():
            shutil.rmtree(d)
        fonts.mkdir(parents=True)
        for f in opt["faces"]:
            shutil.copy(BUILT / opt["build"] / "fonts" / f["file"], fonts / f["file"])
        for lic, srcpath in opt["licences"].items():
            shutil.copy(SRC / srcpath, fonts / lic)
        refs = "\n".join(
            f"    {{ name: {q(x['name'])}, url: {q(x['url'])}, what: {q(x['what'])} }}," for x in opt["refs"]
        )
        faces = []
        for f in opt["faces"]:
            parts = [f"family: {q(f['family'])}", f"src: font({q(f['file'])})", f"weight: {q(f['weight'])}"]
            if f.get("style"):
                parts.append(f"style: {q(f['style'])}")
            ur = f.get("unicodeRange", "LATIN")
            parts.append("unicodeRange: LATIN" if ur == "LATIN" else f"unicodeRange: {q(ur)}")
            faces.append("    { " + ", ".join(parts) + " },")
        steps = opt["steps"]
        tok = dict(opt["tokens"])
        sizes = []
        for k, v in steps.items():
            name = k.replace("--step-", "")
            if isinstance(v, str):
                tok[k] = v
                sizes.append(f"{name} as round {opt['origin']}")
            elif len(v) == 3:
                tok[k] = snapped(*v)
                sizes.append(f"{name} {r(v[0])}->{r(v[1])} on a {r(v[2])} grid")
            else:
                tok[k] = fluid(*v)
                sizes.append(f"{name} {r(v[0])}->{r(v[1])}")
        size_note = "Sizes in px at a 390 -> 1440 viewport: " + "; ".join(sizes) + "."
        disp_family = tok["--font-display"].split("'")[1]
        disp_file = next(f["file"] for f in opt["faces"] if f["family"] == disp_family and "unicodeRange" not in f)
        disp_font = load(fonts / disp_file, float(tok["--display-weight"]))
        tok["--display-advance"] = f"{advance(disp_font, float(tok['--display-tracking'].replace('em', '')), tok['--display-transform'] == 'uppercase'):.3f}"
        order = [
            "--font-display", "--font-body", "--font-ui", "--font-mono",
            "--display-weight", "--display-tracking", "--display-leading", "--display-transform", "--display-advance",
            "--body-weight", "--body-leading", "--measure",
            "--step--1", "--step-0", "--step-1", "--step-2", "--step-3", "--step-4", "--step-5",
        ]
        missing = [k for k in order if k not in tok]
        assert not missing, (opt["id"], missing)
        tokens = "\n".join(f"    {q(k)}: {q(tok[k])}," for k in order)
        (d / "index.ts").write_text(
            TS.format(
                comment=opt["comment"] + "\n// " + size_note,
                latin=LATIN,
                id=opt["id"],
                label=q(opt["label"]),
                summary=q(opt["summary"]),
                origin=opt["origin"],
                refs=refs,
                faces="\n".join(faces),
                tokens=tokens,
                license=q(opt["license"]),
            )
        )
        kb = sum((fonts / f["file"]).stat().st_size for f in opt["faces"]) / 1024
        print(f"{opt['id']:22s} {kb:6.1f} KB  {len(opt['faces'])} faces")


if __name__ == "__main__":
    main()
