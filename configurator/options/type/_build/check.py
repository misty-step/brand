"""Browser-free checks for every generated type option (run after gen_options.py).

    python3 check.py

Fails on: a --font-* token whose first family has no face; a missing or non-woff2 file; a token
weight outside its face's range; a Latin face missing letters, digits or the punctuation the pages
use; a missing or non-OFL licence text; body outside 16-19px or any step under 12px at 390/1440.
Reports: font KB, display/body ratio at 1440, and h1 line counts from a word-wrap simulation on the
font's own advances, at the option's --step-5 and at the size heroes pick with --display-advance.
"""
import re
import sys
from pathlib import Path

from fontTools.ttLib import TTFont

from metrics import SAMPLE, lines, load, size_at

HERE = Path(__file__).parent
TYPE = HERE.parent
NEEDED = set(map(ord, "ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789 .,:;!?'\"()/$%&+-=@#*_“”‘’…€×"))
COLUMNS = ((390, 350), (1440, 820), (1440, 1100))
FIT = 0.6  # heroes size the h1 at min(--step-5, 100cqi / (chars x advance x FIT))
FACE = re.compile(r'family: "([^"]+)", src: font\("([^"]+)"\), weight: "([^"]+)"(?:, style: "[^"]+")?(?:, unicodeRange: (LATIN|"[^"]+"))?')
fails = 0


def bad(opt, msg):
    global fails
    fails += 1
    print(f"FAIL {opt}: {msg}")


for d in sorted(p for p in TYPE.iterdir() if (p / "index.ts").exists()):
    t = (d / "index.ts").read_text()
    if "Generated by options/type/_build" not in t:
        continue  # hand-written options (the plain baseline) are not ours to check
    tok = dict(re.findall(r'"(--[\w-]+)": "([^"]*)"', t))
    fams = {}
    for fam, file, w, ur in FACE.findall(t):
        lo, hi = (list(map(float, w.split())) * 2)[:2]
        fams.setdefault(fam, []).append((file, lo, hi, ur))
        p = d / "fonts" / file
        if not p.exists():
            bad(d.name, f"missing {file}")
            continue
        if p.read_bytes()[:4] != b"wOF2":
            bad(d.name, f"{file} is not woff2")
        if ur == "LATIN":
            cmap = TTFont(p).getBestCmap()
            missing = "".join(chr(c) for c in sorted(NEEDED) if c not in cmap)
            if missing:
                bad(d.name, f"{file} lacks {missing}")
    for role, wtok in (("--font-display", "--display-weight"), ("--font-body", "--body-weight"), ("--font-ui", None), ("--font-mono", None)):
        first = re.match(r"'([^']+)'", tok[role]).group(1)
        if first not in fams:
            bad(d.name, f"{role} family {first!r} has no face")
        elif wtok and not any(lo <= float(tok[wtok]) <= hi for _, lo, hi, _ in fams[first]):
            bad(d.name, f"{wtok} {tok[wtok]} outside the {first} faces")
    lic = sorted((d / "fonts").glob("OFL-*.txt"))
    if not lic:
        bad(d.name, "no licence files")
    for lf in lic:
        if "SIL OPEN FONT LICENSE" not in lf.read_text().upper():
            bad(d.name, f"{lf.name} is not the OFL")
    s = {k: (size_at(v, 390), size_at(v, 1440)) for k, v in tok.items() if k.startswith("--step")}
    body = s["--step-0"]
    if not (16 <= body[0] <= 19 and 16 <= body[1] <= 19):
        bad(d.name, f"body {body[0]:.1f}/{body[1]:.1f}px outside 16-19px")
    smallest = min(v for pair in s.values() for v in pair)
    if smallest < 12:
        bad(d.name, f"text under 12px ({smallest:.1f})")
    kb = sum(p.stat().st_size for p in (d / "fonts").glob("*.woff2")) / 1024
    ratio = s["--step-5"][1] / body[1]

    disp = re.match(r"'([^']+)'", tok["--font-display"]).group(1)
    file = next(f for f, _, _, ur in fams[disp] if ur == "LATIN")
    font = load(d / "fonts" / file, float(tok["--display-weight"]))
    tr = float(tok["--display-tracking"].replace("em", ""))
    upper = tok["--display-transform"] == "uppercase"
    adv = float(tok["--display-advance"])
    own, fit = [], []
    for vw, col in COLUMNS:
        step5 = size_at(tok["--step-5"], vw)
        for h in SAMPLE:
            text = h.upper() if upper else h
            own.append(lines(font, text, step5, tr, col))
            fit.append(lines(font, text, max(24, min(step5, col / (len(h) * adv * FIT))), tr, col))
    print(f"ok   {d.name:22s} {kb:6.1f} KB  body {body[0]:.0f}/{body[1]:.0f}px  h1 {s['--step-5'][0]:.1f}/{s['--step-5'][1]:.1f}px "
          f"({ratio:.2f}x)  h1 over 2 lines: {sum(n > 2 for n in own)}/{len(own)} at --step-5, {sum(n > 2 for n in fit)}/{len(fit)} fitted")
print("FAIL" if fails else "PASS", f"({fails} failures)")
sys.exit(1 if fails else 0)
