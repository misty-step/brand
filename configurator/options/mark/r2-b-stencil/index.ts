import type { MarkOption } from '../../../src/contract';
import { esc } from '../../../src/html';
import { cells, quiet, runs, settle, svg } from '../_lib/mark';
import { DISPLAY, M_16, M_32, M_FULL, NAV, STRAIGHT } from './drawing';

// Stencil step. The name drawn from Sofia Sans Extra Condensed outlines with one stencil cut through it, the path
// the mist takes. The cut steps up by exactly its own thickness at the word break, so MISTY is cut low and the word
// it leads to (STEP, STACK) is cut one step higher. Letters never move; only the cut steps.
//
// Construction (drawing.ts is generated by ../r2-b-src/build.py; font units, cap height H = 655):
// - Display logotype, `logotype()`: wght 760. The letters set the cut. Its band runs from the top of the S spine
//   (y 410) to the underside of the P bowl (y 548): 138 units, split into two cuts of t = 69 (H / 9.5). MISTY:
//   410..479. STEP / STACK: 479..548. The step's x is the centre of the word space (the Y|S join in MISTYSTACK).
//   E's top arm, T's bar and the S top sit on the upper cut; the S spine sits under the lower one; E's middle arm,
//   A's bar and K's junction lie clear below. Both closed counters (P, A) cross the upper cut, so the logotype is a
//   working stencil. Fragments shorter than t are removed (the tips of the S and C terminals).
// - Only band: lower bands hit A's bar (138..236), K's junction (200..372), P's bowl foot (230..338) or M's vertex.
//   Lowercase mistystack was drawn and dropped: its only clean band (s spine top 322 to t bar underside 392) allows
//   a 35-unit cut (H / 19), a hairline at display size and gone in the nav. Caps read better at 390.
// - Rule: the cut appears only where it reads as made. The symbol carries the stepped cut at every size; the name
//   is cut from a 28 px cap up (hero, footer statement, social cards, print). In the nav and on phones the name is
//   solid caps (`wordmark()`: wght 800, 14 px cap, tracked +0.5 px, kerned by hand): at that size the band is
//   2.95 px, two 2 px cuts detached the T bar (STEP read as SIEP at 1x) and one read as a strikethrough.
// - Symbol: the wordmark's M (wght 800) cut through the middle, its left half low and its right half one full cut
//   higher, stepping at the vertex. On a 28-unit M the left cut is 12..14 above the baseline and the right 16..18,
//   so the two cuts sit on clearly different rows. 16 px: drawn on the pixel grid, stems 3 px, deep V 2 px, cut and
//   step 1 px (rows 8 and 7). 32 px: drawn on the pixel grid, stems hinted to 5 px, cut 2 px, cuts 2 px apart.
//   48 px up: the same M and cut in vector, in a 32/28 box.
// - Lockup: the 32 px symbol's M stands 28 px, 2x the name's 14 px cap, centred on it; symbol to name 10 px (two
//   M stems). Clear space around the lockup: one M stem width (5 px at the nav size, 1/5.6 of the M's height).
// - animateIn: the cut starts straight (both halves on the left's rows) and the right half steps up once, a hard
//   cut at 280 ms, ending on the finished drawing.
// Collisions checked (2026-10-29): sliced and stencil wordmarks are a known genre (logosandtypes.com sliced
// technique, Esprit by John Casado, Helldivers 2, VASA's NSA specimen with one shared diagonal cut, Design Shack
// "sliced text", Anytime Fitness's old striped wordmark), and military and industrial stencil M marks are common.
// None steps its cut at a word break or at an M's vertex; the nearest are single straight slices and
// slice-and-shift. Split-M monograms with an offset half are common (LogoSymbol "Cool Double M"); this M is never
// split or shifted, only cut.

type Name = keyof typeof NAV;
const NAV_CAP = 14;
const STEP_AT_MS = 280;
const key = (name: string): Name | null => {
  const k = name.trim().toUpperCase().replace(/\s+/g, ' ');
  return k in NAV ? (k as Name) : null;
};
const ink = (d: string) => `<path fill="currentColor" d="${d}"/>`;

function symbol(size: number): string {
  const cls = 'mk mk-r2b-stencil';
  if (size <= 24) return svg({ viewBox: [16, 16], width: size, height: size, cls, crisp: true, body: ink(runs(cells(M_16).get('#') ?? [])) });
  if (size < 48) return svg({ viewBox: [32, 32], width: size, height: size, cls, crisp: true, body: ink(runs(cells(M_32).get('#') ?? [])) });
  return svg({ viewBox: M_FULL.vb, width: size, height: size, cls, body: ink(M_FULL.d) });
}

/** The cut logotype for a 28 px cap and up (hero, footer statement, social cards, print); null for other names. */
export function logotype(name: string, capPx: number): string | null {
  const k = key(name);
  if (!k) return null;
  const dr = DISPLAY[k], h = (capPx * dr.vb[1]) / 655;
  return svg({ viewBox: dr.vb, width: +((h * dr.vb[0]) / dr.vb[1]).toFixed(2), height: +h.toFixed(2), cls: 'wm wm-r2b-stencil', label: name, body: ink(dr.d) });
}

export default {
  id: 'r2-b-stencil',
  layer: 'mark',
  label: 'Stencil step',
  origin: 'r2',
  summary: 'The name drawn from the baseline face with one stencil cut through it, the path the mist takes, stepping up exactly one cut at the word break; the M carries the same step at its vertex.',
  refs: [
    { name: 'Brass Hands', url: 'https://www.brasshands.com', what: 'Identity drawn to pass a shipping-container test: one colour, no hairlines, lettering that survives a stencil. Here the stencil cut is the idea itself, so the logotype is a working stencil.' },
    { name: 'Esprit by John Casado (1978)', url: 'https://bpando.org/2024/08/03/esprit-branding-logo-1978-john-casado/', what: 'A grotesque made ownable by a few deliberate cuts rather than a new typeface, with weights drawn per size so the cuts still read small.' },
  ],
  svg: ({ size }) => symbol(size),
  wordmark: ({ name }) => {
    const k = key(name);
    if (!k) return esc(name);
    const dr = NAV[k];
    return svg({ viewBox: dr.vb, width: +((NAV_CAP * dr.vb[0]) / dr.vb[1]).toFixed(2), height: NAV_CAP, cls: 'wm wm-r2b-stencil', label: name, body: ink(dr.d) });
  },
  // The cut starts straight, then the right half steps up one unit: a hard cut at 280 ms to the finished drawing.
  animateIn: (el, ctx) => {
    const svgEl = el.querySelector('svg');
    const path = svgEl?.querySelector('path');
    if (quiet(ctx) || !svgEl || !path) return () => {};
    const box = svgEl.getAttribute('viewBox');
    const straight = box === '0 0 16 16' ? runs(cells(STRAIGHT.m16).get('#') ?? [])
      : box === '0 0 32 32' ? runs(cells(STRAIGHT.m32).get('#') ?? []) : STRAIGHT.full;
    const first = path.cloneNode() as SVGPathElement;
    first.setAttribute('d', straight);
    path.after(first);
    const timing = { duration: 1, delay: STEP_AT_MS, easing: 'steps(1, end)' };
    const anims = [
      path.animate([{ visibility: 'hidden' }, { visibility: 'visible' }], { ...timing, fill: 'backwards' }),
      first.animate([{ visibility: 'visible' }, { visibility: 'hidden' }], { ...timing, fill: 'forwards' }),
    ];
    const done = () => first.remove();
    anims[1].finished.then(done, done);
    const cancel = settle(anims);
    return () => { cancel(); done(); };
  },
  css: `
html[data-mark="r2-b-stencil"] .brand { gap: 10px; }
html[data-mark="r2-b-stencil"] .brand-mark svg { display: block; width: 32px; height: 32px; }
html[data-mark="r2-b-stencil"] .brand-name { display: block; line-height: 0; }
html[data-mark="r2-b-stencil"] .brand-name svg { display: block; width: auto; height: ${NAV_CAP}px; }
`,
} satisfies MarkOption & { css: string };
